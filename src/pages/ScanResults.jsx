import { useState, useEffect, useCallback } from 'react';
import { useParams, Link } from 'react-router-dom';
import { ChevronDown, ChevronUp, Copy, Check, FileDown, ArrowLeft } from 'lucide-react';
import SEOHead from '@/components/seo/SEOHead';
import PageHeader from '@/components/ui/PageHeader';
import Breadcrumbs from '@/components/ui/Breadcrumbs';
import SeverityPill from '@/components/ui/SeverityPill';
import StatTile from '@/components/ui/StatTile';
import ErrorState from '@/components/ui/ErrorState';
import { SkeletonCard, SkeletonTable } from '@/components/ui/SkeletonLoader';
import { scanApi, reportApi } from '@/services/api';
import { MOCKS_ENABLED, mockScanResults } from '@/mocks/data';
import { formatDate, formatDuration, severityWeight, copyToClipboard } from '@/utils/helpers';
import { AlertTriangle, ShieldAlert, ShieldCheck, Info } from 'lucide-react';
import TextRoll from '@/components/ui/text-roll';

const CATEGORY_LABELS = {
  prompt_injection: 'Prompt Injection',
  data_leakage: 'Data Leakage',
  tool_abuse: 'Tool Abuse',
  memory_poisoning: 'Memory Poisoning',
  jailbreak: 'Jailbreak',
  data_exfiltration: 'Data Exfiltration',
  api_manipulation: 'API Manipulation',
};

export default function ScanResults() {
  const { scanId } = useParams();
  const [results, setResults] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);
  const [retrying, setRetrying] = useState(false);
  const [expandedFindings, setExpandedFindings] = useState(new Set());
  const [downloading, setDownloading] = useState(false);

  const fetchResults = useCallback(async () => {
    try {
      setError(null);
      if (MOCKS_ENABLED) {
        setResults({ ...mockScanResults, id: scanId });
        setLoading(false);
        setRetrying(false);
        return;
      }
      const res = await scanApi.getResults(scanId);
      setResults(res.data);
    } catch (err) {
      setError(err.userMessage || 'Failed to load scan results.');
    } finally {
      setLoading(false);
      setRetrying(false);
    }
  }, [scanId]);

  useEffect(() => {
    fetchResults();
  }, [fetchResults]);

  const handleRetry = () => {
    setRetrying(true);
    setLoading(true);
    fetchResults();
  };

  const toggleFinding = (id) => {
    setExpandedFindings((prev) => {
      const next = new Set(prev);
      if (next.has(id)) next.delete(id);
      else next.add(id);
      return next;
    });
  };

  const handleDownloadPdf = async () => {
    setDownloading(true);
    try {
      if (MOCKS_ENABLED) {
        await new Promise((r) => setTimeout(r, 600));
        const pdfContent = `%PDF-1.4
1 0 obj << /Type /Catalog /Pages 2 0 R >> endobj
2 0 obj << /Type /Pages /Kids [3 0 R] /Count 1 >> endobj
3 0 obj << /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >> endobj
4 0 obj << /Length 300 >> stream
BT
/F1 20 Tf
50 720 Td
(AgentLock Security Vulnerability Report) Tj
/F1 12 Tf
0 -35 Td
(Scan ID: ${scanId}) Tj
0 -20 Td
(Agent: ${results?.agent_name || 'AI Agent'}) Tj
0 -20 Td
(Summary: ${results?.summary?.total || 0} findings - ${results?.summary?.critical || 0} critical) Tj
0 -20 Td
(Generated by AgentLock Platform) Tj
ET
endstream endobj
5 0 obj << /Type /Font /Subtype /Type1 /BaseFont /Helvetica >> endobj
xref
0 6
0000000009 00000 n 
0000000058 00000 n 
0000000115 00000 n 
0000000244 00000 n 
0000000596 00000 n 
trailer << /Size 6 /Root 1 0 R >>
startxref
670
%%EOF`;
        const blob = new Blob([pdfContent], { type: 'application/pdf' });
        const url = window.URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = `agentlock-report-${scanId}.pdf`;
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);
        window.URL.revokeObjectURL(url);
        return;
      }
      const res = await reportApi.downloadPdf(scanId);
      const url = window.URL.createObjectURL(new Blob([res.data], { type: 'application/pdf' }));
      const a = document.createElement('a');
      a.href = url;
      a.download = `agentlock-report-${scanId}.pdf`;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      window.URL.revokeObjectURL(url);
    } catch (err) {
      alert(err.userMessage || 'Failed to download report.');
    } finally {
      setDownloading(false);
    }
  };

  if (loading) {
    return (
      <>
        <SEOHead title="Scan Results" noIndex />
        <Breadcrumbs items={[{ label: 'Dashboard', to: '/dashboard' }, { label: 'Scans' }, { label: scanId }, { label: 'Results' }]} />
        <div className="flex flex-col gap-6">
          <div className="grid grid-cols-2 lg:grid-cols-5 gap-4">
            {Array.from({ length: 5 }).map((_, i) => <SkeletonCard key={i} lines={1} />)}
          </div>
          <SkeletonTable rows={5} columns={3} />
        </div>
      </>
    );
  }

  if (error) {
    return (
      <>
        <SEOHead title="Scan Results" noIndex />
        <Breadcrumbs items={[{ label: 'Dashboard', to: '/dashboard' }, { label: 'Scans' }, { label: scanId }, { label: 'Results' }]} />
        <ErrorState title="Failed to load results" message={error} onRetry={handleRetry} retrying={retrying} />
      </>
    );
  }

  // Sort findings: critical first
  const sortedFindings = [...(results?.findings || [])].sort(
    (a, b) => severityWeight(b.severity) - severityWeight(a.severity)
  );

  // Group by category
  const groupedFindings = sortedFindings.reduce((acc, finding) => {
    const cat = finding.category || 'other';
    if (!acc[cat]) acc[cat] = [];
    acc[cat].push(finding);
    return acc;
  }, {});

  const summary = results?.summary || {};

  return (
    <>
      <SEOHead title={`Results: ${results?.agent_name || scanId}`} noIndex />
      <Breadcrumbs items={[
        { label: 'Dashboard', to: '/dashboard' },
        { label: 'Scans' },
        { label: scanId, to: `/scans/${scanId}` },
        { label: 'Results' },
      ]} />
      <PageHeader title="Scan Results" description={`${results?.agent_name || 'Agent'} scan completed ${formatDate(results?.completed_at)}`}>
        <button
          onClick={handleDownloadPdf}
          disabled={downloading}
          className="neu-btn inline-flex items-center gap-2 min-h-[40px]"
        >
          <FileDown size={18} aria-hidden="true" />
          {downloading ? 'Downloading...' : 'Download PDF'}
        </button>
      </PageHeader>

      {/* Summary tiles */}
      <div className="grid grid-cols-2 lg:grid-cols-5 gap-4 mb-8">
        <StatTile label="Total Findings" value={summary.total || 0} icon={ShieldAlert} />
        <StatTile label="Critical" value={summary.critical || 0} icon={AlertTriangle} />
        <StatTile label="High" value={summary.high || 0} icon={AlertTriangle} />
        <StatTile label="Medium" value={summary.medium || 0} icon={Info} />
        <StatTile label="Low" value={summary.low || 0} icon={ShieldCheck} />
      </div>

      {/* Duration */}
      {results?.started_at && results?.completed_at && (
        <p className="text-xs mb-6" style={{ fontFamily: 'var(--font-mono)', color: 'var(--color-text-muted)' }}>
          Scan duration: {formatDuration(results.started_at, results.completed_at)}
        </p>
      )}

      {/* Findings by category */}
      {Object.keys(groupedFindings).length === 0 ? (
        <div className="neu-well p-8 text-center">
          <ShieldCheck size={40} style={{ color: 'var(--color-severity-low)' }} aria-hidden="true" className="mx-auto mb-3" />
          <p className="text-sm" style={{ color: 'var(--color-text-secondary)' }}>No vulnerabilities found. This agent passed all tests.</p>
        </div>
      ) : (
        <div className="flex flex-col gap-10">
          {Object.entries(groupedFindings).map(([category, findings]) => (
            <section key={category}>
              <h2 className="text-lg font-semibold mb-4 flex items-center justify-between text-cream uppercase" style={{ fontFamily: 'var(--font-heading)' }}>
                <TextRoll stagger={0.012} duration={0.2}>
                  {(CATEGORY_LABELS[category] || category).toUpperCase()}
                </TextRoll>
                <span className="text-xs font-mono text-cream-soft font-normal" style={{ fontFamily: 'var(--font-mono)' }}>
                  {findings.length} finding{findings.length !== 1 ? 's' : ''}
                </span>
              </h2>

              <div className="flex flex-col gap-4">
                {findings.map((finding, index) => (
                  <FindingCard
                    key={finding.id}
                    finding={finding}
                    expanded={expandedFindings.has(finding.id)}
                    onToggle={() => toggleFinding(finding.id)}
                    isFirst={index === 0}
                    isCritical={finding.severity === 'critical'}
                  />
                ))}
              </div>
            </section>
          ))}
        </div>
      )}

      {/* Back link */}
      <div className="mt-10">
        <Link
          to={results?.agent_id ? `/agents/${results.agent_id}` : '/dashboard'}
          className="neu-btn inline-flex items-center gap-2 min-h-[40px] no-underline"
        >
          <ArrowLeft size={18} aria-hidden="true" />
          {results?.agent_id ? 'Back to Agent' : 'Back to Dashboard'}
        </Link>
      </div>
    </>
  );
}

/* ── Finding Card ── */
function FindingCard({ finding, expanded, onToggle, isFirst, isCritical }) {
  const [copied, setCopied] = useState(false);

  const handleCopy = async (text) => {
    const ok = await copyToClipboard(text);
    if (ok) {
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    }
  };

  return (
    <div
      className={`neu-card shadow-raised-md overflow-hidden ${
        isCritical && isFirst ? 'animate-critical-pulse' : 'animate-finding-enter'
      }`}
      style={{ animationDelay: isFirst ? '0ms' : '100ms' }}
    >
      {/* Header */}
      <button
        type="button"
        onClick={onToggle}
        className="w-full flex items-center justify-between p-5 min-h-[48px] text-left"
        aria-expanded={expanded}
      >
        <div className="flex items-center gap-3 min-w-0">
          <SeverityPill severity={finding.severity} />
          <span className="text-sm font-medium truncate" style={{ color: 'var(--color-text-primary)' }}>
            {finding.title}
          </span>
        </div>
        {expanded ? (
          <ChevronUp size={18} style={{ color: 'var(--color-text-muted)' }} aria-hidden="true" className="shrink-0" />
        ) : (
          <ChevronDown size={18} style={{ color: 'var(--color-text-muted)' }} aria-hidden="true" className="shrink-0" />
        )}
      </button>

      {/* Expanded details */}
      {expanded && (
        <div className="px-5 pb-5 flex flex-col gap-5">
          {/* Description */}
          <div>
            <h4 className="text-xs uppercase tracking-wider mb-2" style={{ color: 'var(--color-text-muted)' }}>Description</h4>
            <p className="text-sm leading-relaxed" style={{ color: 'var(--color-text-secondary)' }}>{finding.description}</p>
          </div>

          {/* Evidence */}
          {finding.evidence && (
            <div>
              <div className="flex items-center justify-between mb-2">
                <h4 className="text-xs uppercase tracking-wider" style={{ color: 'var(--color-text-muted)' }}>Evidence</h4>
                <button
                  onClick={() => handleCopy(finding.evidence)}
                  className="neu-btn flex items-center gap-1 min-h-[32px] px-3 text-xs"
                  aria-label="Copy evidence to clipboard"
                >
                  {copied ? <Check size={14} style={{ color: 'var(--color-severity-low)' }} /> : <Copy size={14} />}
                  <span>{copied ? 'Copied' : 'Copy'}</span>
                </button>
              </div>
              <div className="neu-well p-4 overflow-x-auto">
                <pre
                  className="text-xs leading-relaxed whitespace-pre-wrap break-words m-0"
                  style={{ fontFamily: 'var(--font-mono)', color: 'var(--color-text-secondary)' }}
                >
                  {finding.evidence}
                </pre>
              </div>
            </div>
          )}

          {/* Impact */}
          {finding.impact && (
            <div>
              <h4 className="text-xs uppercase tracking-wider mb-2" style={{ color: 'var(--color-text-muted)' }}>Impact</h4>
              <p className="text-sm leading-relaxed" style={{ color: 'var(--color-text-secondary)' }}>{finding.impact}</p>
            </div>
          )}

          {/* Remediation */}
          {finding.remediation && (
            <div>
              <h4 className="text-xs uppercase tracking-wider mb-2" style={{ color: 'var(--color-text-muted)' }}>Remediation</h4>
              <p className="text-sm leading-relaxed" style={{ color: 'var(--color-text-secondary)' }}>{finding.remediation}</p>
            </div>
          )}
        </div>
      )}
    </div>
  );
}
