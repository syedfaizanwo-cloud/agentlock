import { useState, useEffect, useCallback } from 'react';
import { FileDown, FileText } from 'lucide-react';
import SEOHead from '@/components/seo/SEOHead';
import PageHeader from '@/components/ui/PageHeader';
import Breadcrumbs from '@/components/ui/Breadcrumbs';
import ErrorState from '@/components/ui/ErrorState';
import EmptyState from '@/components/ui/EmptyState';
import SeverityPill from '@/components/ui/SeverityPill';
import { SkeletonTable } from '@/components/ui/SkeletonLoader';
import { reportApi } from '@/services/api';
import { MOCKS_ENABLED, mockReports } from '@/mocks/data';
import { formatDate } from '@/utils/helpers';
import TextRoll from '@/components/ui/text-roll';

export default function Reports() {
  const [reports, setReports] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);
  const [retrying, setRetrying] = useState(false);
  const [downloadingId, setDownloadingId] = useState(null);
  const [filter, setFilter] = useState('ALL');

  const filteredReports = reports.filter((r) => {
    if (filter === 'CRITICAL') return (r.severity_summary?.critical || 0) > 0;
    if (filter === 'HIGH') return (r.severity_summary?.high || 0) > 0;
    return true;
  });

  const fetchReports = useCallback(async () => {
    try {
      setError(null);
      if (MOCKS_ENABLED) {
        setReports(mockReports);
        setLoading(false);
        setRetrying(false);
        return;
      }
      // Reports come from scan results - use the dashboard stats endpoint
      // or a dedicated reports endpoint if available
      const res = await reportApi.downloadPdf('list').catch(() => ({ data: [] }));
      setReports(Array.isArray(res.data) ? res.data : []);
    } catch (err) {
      // If no dedicated reports endpoint, show mock data or empty
      if (MOCKS_ENABLED) {
        setReports(mockReports);
      } else {
        setError(err.userMessage || 'Failed to load reports.');
      }
    } finally {
      setLoading(false);
      setRetrying(false);
    }
  }, []);

  useEffect(() => {
    fetchReports();
  }, [fetchReports]);

  const handleRetry = () => {
    setRetrying(true);
    setLoading(true);
    fetchReports();
  };

  const handleDownload = async (reportId) => {
    setDownloadingId(reportId);
    try {
      if (MOCKS_ENABLED) {
        await new Promise((r) => setTimeout(r, 600));
        const report = reports.find((r) => r.id === reportId);
        const pdfContent = `%PDF-1.4
1 0 obj << /Type /Catalog /Pages 2 0 R >> endobj
2 0 obj << /Type /Pages /Kids [3 0 R] /Count 1 >> endobj
3 0 obj << /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >> endobj
4 0 obj << /Length 300 >> stream
BT
/F1 20 Tf
50 720 Td
(AgentLock Security Vulnerability Report) Tj
/F1 12 Tf
0 -35 Td
(Report ID: ${reportId}) Tj
0 -20 Td
(Agent: ${report?.agent_name || 'AI Agent'}) Tj
0 -20 Td
(Findings: ${report?.findings_count || 0} vulnerabilities detected) Tj
0 -20 Td
(Generated by AgentLock Platform) Tj
ET
endstream endobj
5 0 obj << /Type /Font /Subtype /Type1 /BaseFont /Helvetica >> endobj
xref
0 6
0000000009 00000 n 
0000000058 00000 n 
0000000115 00000 n 
0000000244 00000 n 
0000000596 00000 n 
trailer << /Size 6 /Root 1 0 R >>
startxref
670
%%EOF`;
        const blob = new Blob([pdfContent], { type: 'application/pdf' });
        const url = window.URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = `agentlock-report-${reportId}.pdf`;
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);
        window.URL.revokeObjectURL(url);
        return;
      }
      const res = await reportApi.downloadPdf(reportId);
      const url = window.URL.createObjectURL(new Blob([res.data], { type: 'application/pdf' }));
      const a = document.createElement('a');
      a.href = url;
      a.download = `agentlock-report-${reportId}.pdf`;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      window.URL.revokeObjectURL(url);
    } catch (err) {
      alert(err.userMessage || 'Failed to download report.');
    } finally {
      setDownloadingId(null);
    }
  };

  return (
    <>
      <SEOHead title="Reports" noIndex />
      <Breadcrumbs items={[{ label: 'Dashboard', to: '/dashboard' }, { label: 'Reports' }]} />
      <PageHeader title="Reports" description="Scan history and vulnerability reports" />

      {error && <ErrorState title="Failed to load reports" message={error} onRetry={handleRetry} retrying={retrying} />}

      {loading && !error && <SkeletonTable rows={5} columns={5} />}

      {!loading && !error && reports.length === 0 && (
        <EmptyState
          title="No reports yet"
          message="Complete a scan to generate your first vulnerability report."
          actionLabel="Start a Scan"
          actionTo="/scans/new"
          icon={FileText}
        />
      )}

      {!loading && !error && reports.length > 0 && (
        <div className="neu-card shadow-raised-md p-0">
          <div className="shadow-inset-sm rounded-t-[14px] px-6 py-3 flex items-center justify-between flex-wrap gap-3">
            <div className="flex items-center gap-4">
              {['ALL', 'CRITICAL', 'HIGH'].map((tab) => (
                <button
                  key={tab}
                  type="button"
                  onClick={() => setFilter(tab)}
                  className={`text-xs font-semibold tracking-wider uppercase px-2 py-1 transition-colors min-h-[32px] ${
                    filter === tab ? 'text-coral' : 'text-cream-soft hover:text-coral'
                  }`}
                  aria-pressed={filter === tab}
                >
                  <TextRoll active={filter === tab} stagger={0.012} duration={0.18}>
                    {tab === 'ALL' ? 'ALL REPORTS' : `${tab} FINDINGS`}
                  </TextRoll>
                </button>
              ))}
            </div>
            <span className="text-xs font-mono text-cream-soft" style={{ fontFamily: 'var(--font-mono)' }}>
              {filteredReports.length} reports
            </span>
          </div>
          <div className="overflow-x-auto">
            <table className="w-full text-left" role="table">
              <thead>
                <tr className="text-xs uppercase tracking-wider" style={{ color: 'var(--color-text-muted)' }}>
                  <th className="px-6 py-3 font-medium">Report ID</th>
                  <th className="px-6 py-3 font-medium">Agent</th>
                  <th className="px-6 py-3 font-medium">Date</th>
                  <th className="px-6 py-3 font-medium">Findings</th>
                  <th className="px-6 py-3 font-medium">Severity</th>
                  <th className="px-6 py-3 font-medium"><span className="sr-only">Actions</span></th>
                </tr>
              </thead>
              <tbody>
                {filteredReports.map((report) => {
                  const totalFindings = report.findings_count || 0;
                  return (
                    <tr
                      key={report.id}
                      className="border-t transition-colors"
                      style={{ borderColor: 'var(--color-shadow-dark)' }}
                      onMouseEnter={(e) => { e.currentTarget.style.boxShadow = 'var(--shadow-inset-sm)'; }}
                      onMouseLeave={(e) => { e.currentTarget.style.boxShadow = 'none'; }}
                    >
                      <td className="px-6 py-4 text-sm" style={{ fontFamily: 'var(--font-mono)', color: 'var(--color-text-secondary)' }}>
                        {report.id}
                      </td>
                      <td className="px-6 py-4 text-sm" style={{ color: 'var(--color-text-primary)' }}>
                        {report.agent_name}
                      </td>
                      <td className="px-6 py-4 text-sm" style={{ color: 'var(--color-text-secondary)' }}>
                        {formatDate(report.created_at)}
                      </td>
                      <td className="px-6 py-4 text-sm" style={{ fontFamily: 'var(--font-mono)', color: 'var(--color-text-primary)' }}>
                        {totalFindings}
                      </td>
                      <td className="px-6 py-4">
                        <div className="flex items-center gap-2 flex-wrap">
                          {report.severity_summary?.critical > 0 && <SeverityPill severity="critical" />}
                          {report.severity_summary?.high > 0 && <SeverityPill severity="high" />}
                          {report.severity_summary?.medium > 0 && <SeverityPill severity="medium" />}
                          {report.severity_summary?.low > 0 && <SeverityPill severity="low" />}
                        </div>
                      </td>
                      <td className="px-6 py-4 text-right">
                        <button
                          onClick={() => handleDownload(report.id)}
                          disabled={downloadingId === report.id}
                          className="neu-btn inline-flex items-center gap-2 min-h-[40px] px-4 text-sm"
                          aria-label={`Download report ${report.id}`}
                        >
                          <FileDown size={16} aria-hidden="true" />
                          {downloadingId === report.id ? 'Downloading...' : 'Download'}
                        </button>
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        </div>
      )}
    </>
  );
}
