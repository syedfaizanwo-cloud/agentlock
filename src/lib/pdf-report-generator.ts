/**
 * AgentLock Client-Side Vector PDF Report Generator
 * Generates an exhaustive, multi-page, print-ready PDF using jsPDF.
 * Only imported dynamically upon user request.
 */

import { Scan, Finding, User, SeverityLevel } from '../types/api';
import { getSeverityCounts, getCategoryCounts, getCategoryBySeverity, SEVERITY_COLORS } from './chart-data';
import { maskSensitiveEvidence } from '../components/results/FindingStepDiagram';

interface GenerateReportOptions {
  scan: Scan;
  findings: Finding[];
  currentUser?: User | null;
  previousScanFindings?: Finding[] | null;
}

export async function generateClientSidePdfReport({
  scan,
  findings,
  currentUser,
  previousScanFindings,
}: GenerateReportOptions): Promise<Blob> {
  const { default: jsPDF } = await import('jspdf');

  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'pt',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 40;
  const contentWidth = pageWidth - margin * 2;

  let y = margin;

  const checkPageBreak = (neededHeight: number) => {
    if (y + neededHeight > pageHeight - margin - 30) {
      doc.addPage();
      y = margin + 20;
    }
  };

  const drawHeaderFooter = (pageNo: number, totalPages: number) => {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(140, 140, 140);
    // Header
    doc.text('AgentLock AI Agent Security Audit Report', margin, 25);
    doc.text(`Scan: #${scan.id}`, pageWidth - margin, 25, { align: 'right' });
    doc.setDrawColor(230, 230, 230);
    doc.setLineWidth(0.5);
    doc.line(margin, 30, pageWidth - margin, 30);

    // Footer
    doc.line(margin, pageHeight - 30, pageWidth - margin, pageHeight - 30);
    doc.text('Confidential - Generated by AgentLock Red Teaming Platform', margin, pageHeight - 18);
    doc.text(`Page ${pageNo} of ${totalPages}`, pageWidth - margin, pageHeight - 18, {
      align: 'right',
    });
  };

  // ----------------------------------------------------
  // SECTION 1: COVER & HEADER
  // ----------------------------------------------------
  // Brand Header
  doc.setFillColor(255, 111, 89); // Coral accent
  doc.roundedRect(margin, y, 28, 28, 4, 4, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(255, 255, 255);
  doc.text('A', margin + 8, y + 20);

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(22);
  doc.setTextColor(10, 22, 51);
  doc.text('AgentLock Security Audit Report', margin + 36, y + 20);

  y += 45;

  // Metadata Grid
  doc.setFillColor(248, 250, 252);
  doc.setDrawColor(226, 232, 240);
  doc.roundedRect(margin, y, contentWidth, 75, 4, 4, 'FD');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(71, 85, 105);

  const col1 = margin + 15;
  const col2 = margin + contentWidth / 2;

  doc.text('Target Agent:', col1, y + 20);
  doc.text('Target Endpoint:', col1, y + 36);
  doc.text('Evaluator:', col1, y + 52);

  doc.text('Scan ID:', col2, y + 20);
  doc.text('Execution Time:', col2, y + 36);
  doc.text('Scan Status:', col2, y + 52);

  doc.setFont('helvetica', 'normal');
  doc.setTextColor(15, 23, 42);

  doc.text(scan.agent_id ? `Agent #${scan.agent_id}` : `Scan #${scan.id}`, col1 + 75, y + 20);
  doc.text(scan.agent_id ? `#${scan.agent_id}` : 'Standard Mock', col1 + 85, y + 36);
  doc.text(currentUser?.email || currentUser?.name || 'Authorized Security Operator', col1 + 60, y + 52);

  doc.text(String(scan.id), col2 + 50, y + 20);
  doc.text(new Date(scan.started_at || scan.created_at).toLocaleString(), col2 + 85, y + 36);
  doc.text(scan.status.toUpperCase(), col2 + 70, y + 52);

  y += 95;

  // ----------------------------------------------------
  // SECTION 2: EXECUTIVE SUMMARY
  // ----------------------------------------------------
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.setTextColor(10, 22, 51);
  doc.text('1. Executive Summary', margin, y);
  y += 18;

  const severityCounts = getSeverityCounts(findings);
  const criticalCount = severityCounts.slices.find((s) => s.key === 'critical')?.count || 0;
  const highCount = severityCounts.slices.find((s) => s.key === 'high')?.count || 0;

  let overallRisk = 'LOW';
  if (criticalCount > 0) overallRisk = 'CRITICAL';
  else if (highCount > 0) overallRisk = 'HIGH';
  else if (findings.length > 0) overallRisk = 'MEDIUM';

  const summaryText =
    `AgentLock completed automated adversarial security testing against agent "${scan.agent_id ? `Agent #${scan.agent_id}` : `Scan #${scan.id}`}". ` +
    `A total of ${findings.length} confirmed vulnerabilities were identified across ${(scan.attack_categories || []).length} evaluated attack categories. ` +
    `The evaluation revealed ${criticalCount} critical-severity exploits and ${highCount} high-severity findings requiring immediate intervention. ` +
    `Immediate remediation is recommended prior to exposing this agentic workflow to untrusted external inputs.`;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(51, 65, 85);
  const splitSummary = doc.splitTextToSize(summaryText, contentWidth);
  doc.text(splitSummary, margin, y);
  y += splitSummary.length * 14 + 15;

  // Metric Cards
  const cardW = (contentWidth - 20) / 3;
  const cardH = 50;

  // Card 1: Total Findings
  doc.setFillColor(248, 250, 252);
  doc.roundedRect(margin, y, cardW, cardH, 4, 4, 'F');
  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139);
  doc.text('TOTAL FINDINGS', margin + 12, y + 18);
  doc.setFontSize(18);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(255, 111, 89);
  doc.text(String(findings.length), margin + 12, y + 40);

  // Card 2: Critical Flaws
  doc.setFillColor(254, 242, 242);
  doc.roundedRect(margin + cardW + 10, y, cardW, cardH, 4, 4, 'F');
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(185, 28, 28);
  doc.text('CRITICAL EXPLOITS', margin + cardW + 22, y + 18);
  doc.setFontSize(18);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(225, 29, 72);
  doc.text(String(criticalCount), margin + cardW + 22, y + 40);

  // Card 3: Overall Posture
  doc.setFillColor(overallRisk === 'CRITICAL' ? 254 : 240, 242, 242);
  doc.roundedRect(margin + (cardW + 10) * 2, y, cardW, cardH, 4, 4, 'F');
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(71, 85, 105);
  doc.text('OVERALL RISK POSTURE', margin + (cardW + 10) * 2 + 12, y + 18);
  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(overallRisk === 'CRITICAL' ? 225 : 15, 29, 72);
  doc.text(overallRisk, margin + (cardW + 10) * 2 + 12, y + 40);

  y += cardH + 25;

  // ----------------------------------------------------
  // SECTION 3: SEVERITY & CATEGORY MATRIX
  // ----------------------------------------------------
  checkPageBreak(120);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.setTextColor(10, 22, 51);
  doc.text('2. Attack Vector Analysis', margin, y);
  y += 18;

  const catCounts = getCategoryCounts(findings);
  catCounts.items.forEach((item) => {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    doc.setTextColor(15, 23, 42);
    doc.text(item.category, margin, y + 10);

    const barX = margin + 130;
    const maxBarW = contentWidth - 190;
    const barW = catCounts.total > 0 ? (item.count / catCounts.total) * maxBarW : 0;

    doc.setFillColor(241, 245, 249);
    doc.roundedRect(barX, y + 2, maxBarW, 10, 2, 2, 'F');

    if (barW > 0) {
      doc.setFillColor(255, 111, 89);
      doc.roundedRect(barX, y + 2, Math.max(4, barW), 10, 2, 2, 'F');
    }

    doc.text(`${item.count} (${item.share}%)`, barX + maxBarW + 10, y + 10);
    y += 18;
  });

  y += 20;

  // ----------------------------------------------------
  // SECTION 4: FINDINGS DETAILS
  // ----------------------------------------------------
  checkPageBreak(100);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.setTextColor(10, 22, 51);
  doc.text('3. Confirmed Vulnerability Findings', margin, y);
  y += 18;

  if (findings.length === 0) {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.setTextColor(100, 116, 139);
    doc.text('No vulnerabilities detected during this evaluation run.', margin, y);
    y += 25;
  } else {
    findings.forEach((finding, idx) => {
      checkPageBreak(130);

      // Finding Header Box
      doc.setFillColor(248, 250, 252);
      doc.setDrawColor(226, 232, 240);
      doc.roundedRect(margin, y, contentWidth, 22, 2, 2, 'FD');

      doc.setFont('helvetica', 'bold');
      doc.setFontSize(9);
      doc.setTextColor(255, 111, 89);
      doc.text(`#${idx + 1}`, margin + 8, y + 15);

      doc.setTextColor(15, 23, 42);
      doc.text(finding.title.slice(0, 70), margin + 30, y + 15);

      doc.setFontSize(8);
      const sevColor = SEVERITY_COLORS[finding.severity.toLowerCase() as SeverityLevel] || '#64748B';
      doc.setTextColor(sevColor);
      doc.text(finding.severity.toUpperCase(), pageWidth - margin - 50, y + 15, { align: 'right' });

      y += 30;

      // Injected Payload
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(8);
      doc.setTextColor(71, 85, 105);
      doc.text('ATTACK PROMPT:', margin, y);
      y += 12;

      doc.setFont('courier', 'normal');
      doc.setFontSize(8);
      doc.setTextColor(30, 41, 59);
      const splitPrompt = doc.splitTextToSize(finding.attack_prompt.slice(0, 300), contentWidth - 10);
      doc.text(splitPrompt, margin + 5, y);
      y += splitPrompt.length * 10 + 8;

      // Evidence (masked)
      checkPageBreak(50);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(8);
      doc.setTextColor(71, 85, 105);
      doc.text('AGENT RESPONSE EVIDENCE:', margin, y);
      y += 12;

      doc.setFont('courier', 'normal');
      doc.setFontSize(8);
      doc.setTextColor(30, 41, 59);
      const masked = maskSensitiveEvidence(finding.evidence);
      const splitEvidence = doc.splitTextToSize(masked.slice(0, 300), contentWidth - 10);
      doc.text(splitEvidence, margin + 5, y);
      y += splitEvidence.length * 10 + 8;

      // Remediation
      checkPageBreak(40);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(8);
      doc.setTextColor(16, 185, 129);
      doc.text('REMEDIATION ACTION:', margin, y);
      y += 12;

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(8);
      doc.setTextColor(51, 65, 85);
      const splitRemediation = doc.splitTextToSize(finding.remediation, contentWidth - 10);
      doc.text(splitRemediation, margin + 5, y);
      y += splitRemediation.length * 11 + 18;
    });
  }

  // ----------------------------------------------------
  // SECTION 5: APPENDIX & METHODOLOGY
  // ----------------------------------------------------
  checkPageBreak(120);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.setTextColor(10, 22, 51);
  doc.text('4. Methodology & Appendix', margin, y);
  y += 18;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(71, 85, 105);

  const methodologyText =
    'AgentLock evaluates AI agents using four primary adversarial vectors:\n' +
    '• Prompt Injection: Direct and indirect instruction overrides and jailbreaks.\n' +
    '• Data Leakage: Extraction of system prompts, secret API keys, and sensitive database credentials.\n' +
    '• Tool Abuse: Parameter manipulation, unauthorized function calls, and privilege escalation.\n' +
    '• Memory Poisoning: Manipulation of agent session state and contamination of vector stores.\n\n' +
    'Disclaimer: Audit findings reflect the behavior of the evaluated target at the timestamp of testing.';

  const splitMeth = doc.splitTextToSize(methodologyText, contentWidth);
  doc.text(splitMeth, margin, y);

  // Add Page Numbers to all pages
  const totalPages = doc.internal.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    drawHeaderFooter(i, totalPages);
  }

  return doc.output('blob');
}
